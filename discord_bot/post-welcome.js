const norm = s => s.toLowerCase().replace(/[^a-zа-яё0-9#-]+/g, ' ').trim();
// Только целым словом: «files» не должен ловить «log-files».
const hasWord = (name, word) => norm(name).split(' ').includes(word);

// Discord режет сообщение на 2000 символах. Документ делится по разделам
// «## …», соседние склеиваются, пока влезают.
function chunks(md, limit = 1900) {
    const parts = md.split(/\n(?=## )/);
    const out = [];
    let cur = '';
    for (const p of parts) {
        if (cur && (cur + '\n\n' + p).length > limit) { out.push(cur); cur = p; }
        else cur = cur ? cur + '\n\n' + p : p;
    }
    if (cur) out.push(cur);
    // раздел длиннее лимита режется по строкам
    return out.flatMap(c => {
        if (c.length <= limit) return [c];
        const res = []; let b = '';
        for (const line of c.split('\n')) {
            if ((b + '\n' + line).length > limit) { res.push(b); b = line; } else b = b ? b + '\n' + line : line;
        }
        if (b) res.push(b);
        return res;
    });
}
