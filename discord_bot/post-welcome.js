const client = new Client({ intents: [GatewayIntentBits.Guilds, GatewayIntentBits.GuildMessages] });
client.once('clientReady', async () => {
    try { await run(); } catch (e) { console.error('❌', e); process.exitCode = 1; }
    client.destroy();
});

async function run() {
    const guild = await client.guilds.fetch(process.env.GUILD_ID);
    const chans = [...(await guild.channels.fetch()).values()].filter(c => c && c.type === ChannelType.GuildText);
    const byWord = w => chans.find(c => hasWord(c.name, w));
    const ids = {
        RULES: byWord('правила'), CODE: byWord('уголовный-кодекс'), LAW: byWord('конституция'),
        PRICE: byWord('прайс-лист'), CONNECT: byWord('как-зайти'), COURT: chans.find(c => c.id === process.env.COURT_CHANNEL_ID),
    };
    const fill = t => t.replace(/<#(RULES|CODE|LAW|PRICE|CONNECT|COURT)>/g, (m, k) => ids[k] ? `<#${ids[k].id}>` : `#${k.toLowerCase()}`);

    console.log(`Режим: ${APPLY ? 'ОТПРАВИТЬ' : 'только план'}\n`);
    for (const p of POSTS) {
        const ch = p.match === 'суд' ? ids.COURT : byWord(p.match);
        if (!ch) { console.log(`?  нет канала «${p.match}»`); continue; }
        const msgs = (typeof p.msgs === 'function' ? p.msgs() : p.msgs).map(fill);
        if (!msgs.length) continue;
        const last = await ch.messages.fetch({ limit: 1 });
        if (last.size) { console.log(`=  #${ch.name}: не пустой, пропущен`); continue; }
        console.log(`+  #${ch.name}: ${msgs.length} сообщ.${p.file ? ' + .mrpack' : ''}`);
        if (!APPLY) continue;
        for (let i = 0; i < msgs.length; i++) {
            const opts = { content: msgs[i], allowedMentions: { parse: [] } };
            if (p.file && i === 0 && fs.existsSync(MRPACK)) opts.files = [MRPACK];
            const m = await ch.send(opts);
            if (i === 0) await m.pin().catch(() => {});
        }
    }
}

