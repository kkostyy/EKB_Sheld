# EKB SHIELD — Границы государств на веб-карте
# ==========================================================
# ВАЖНО: Squaremap/Pl3xMap САМИ ПО СЕБЕ не умеют рисовать
# произвольные полигоны из конфига — это делается либо через:
#   а) их Java Marker API (нужен отдельный плагин-код), либо
#   б) WorldGuard-регионы + аддон-мост (squaremap-worldguard /
#      Pl3xMap-WorldGuard), который автоматически отрисовывает
#      все зарегистрированные регионы WorldGuard на карте.
#
# Раз сервер работает без приват-команд (/claim), WorldGuard
# используется ТОЛЬКО как визуальный маркер территории —
# без выдачи игрокам флагов защиты (build/pvp остаются
# отключены), чтобы не противоречить Конституции RP.
# ==========================================================

# --- Установка (один раз) ---
# 1. Скачать WorldGuard + WorldEdit (зависимость).
# 2. Скачать аддон-мост для отрисовки регионов на карте
#    (актуальное название и совместимость с 26.1.2 проверить
#    на SpigotMC/Modrinth — плагин моложе моих данных обучения).

# --- Регистрация территории государства (пример, 8x8 чанков = 128x128 блоков) ---
# Синтаксис: /rg define <id> -w <world>
# Границы задаются двумя угловыми точками через WorldEdit (//pos1, //pos2)

# Пример для государства "Северный Альянс" с центром в 0,0:
# //pos1 -64,-64
# //pos2 63,63
# /rg define severny_alyans

# Отключаем все защитные флаги — регион ТОЛЬКО для визуализации:
# /rg flag severny_alyans build allow
# /rg flag severny_alyans pvp allow
# /rg flag severny_alyans entry allow
# /rg flag severny_alyans exit allow

# Задаём цвет обводки/название для карты (зависит от конкретного аддона-моста):
# /rg setpriority severny_alyans 1
# /rg flag severny_alyans -- (аддон обычно берёт цвет из региональных мета-данных)

